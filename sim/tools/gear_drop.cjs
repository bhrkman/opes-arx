/* ============================================================================================
   THE GEAR DROP (ruled, the tier pass): every role exists at every tier. A tier-one sniper is
   worse than a tier-four sniper, but there is always a sniper — so that when the Armoury gates
   a young OA to tiers one and two, it is gated to worse kit, not to half a game.

   This tool is run ONCE to write the new models into data/items.json, and is kept so the drop
   is legible and repeatable: every new weapon is built on its type's nearest existing model and
   scaled to its tier; armour and sidearms are authored whole; mods and consumables are RE-TIERED
   rather than invented, because the fight reads consumables by id. Formula prices are
   regenerated by the catalogue's own formula afterwards, as the suite demands.

   node sim/tools/gear_drop.cjs            -> rewrites data/items.json (idempotent: skips ids already present)
   ============================================================================================ */
const fs = require('fs');
const path = require('path');
const FILE = path.join(__dirname, '../../data/items.json');
const data = JSON.parse(fs.readFileSync(FILE, 'utf8'));
const L = data.items;
const have = new Set(L.map(i => i.id));

/* the tier curve: power relative to tier three */
const POW = { 1: 0.75, 2: 0.87, 3: 1.0, 4: 1.25, 5: 1.5 };
/* the tags a plain, early model keeps — what makes the type what it is, and nothing clever */
const PLAIN_TAGS = new Set(['burst', 'area', 'nonlethal', 'single_shot', 'cover_shred']);
/* a type's pen at the top end: heavy guns punch through, the rest barely */
const HEAVY = new Set(['Anti-Materiel', 'Long Rifles', 'Close-Quarters', 'Marksman Rifles']);

function template(type, family, tier) {
  const same = L.filter(i => i.slot === 'primary' && i.type === type);
  const fam = same.filter(i => i.family === family);
  const pool = fam.length ? fam : same;
  return pool.slice().sort((a, b) => Math.abs(a.tier - tier) - Math.abs(b.tier - tier) || (a.tier - b.tier))[0];
}

function weapon(spec) {
  const t = template(spec.type, spec.family, spec.tier);
  const e = JSON.parse(JSON.stringify(t.effects));
  e.power = Math.max(2, Math.round((e.power || 4) * POW[spec.tier] / POW[t.tier]));
  if (spec.tier <= 2) { e.pen = 0; e.tags = (e.tags || []).filter(x => PLAIN_TAGS.has(x)); }
  else if (spec.tier >= 4) e.pen = Math.max(e.pen || 0, HEAVY.has(spec.type) ? spec.tier - 3 : (spec.tier === 5 ? 1 : 0));
  if (spec.tier === 5) e.pen = Math.min(3, e.pen);
  if (spec.family === 'energy' && t.family !== 'energy') {
    e.damage = 'energy'; e.charge = e.mag || 12; e.noise = 1; e.reload = Math.max(2, e.reload || 1);
  } else if (spec.family === 'ballistic' && t.family === 'energy') {
    e.damage = spec.type === 'Launchers' ? 'explosive' : 'ballistic'; delete e.charge; e.noise = 2;
    e.tags = (e.tags || []).filter(x => ['emp', 'disorient', 'burn', 'plasma'].indexOf(x) < 0);
  }
  if (spec.type === 'Stun-Grade') { e.tags = Array.from(new Set(['nonlethal'].concat(e.tags || []))); }
  /* A TIER IS A BETTER GUN, NOT A LOUDER ONE. Power moves a wound's severity by three-quarters of a point
     on a hundred, so the ladder is carried by how a gun handles: steadier in the hand, quicker to the
     shot, a deeper magazine — each tier above the template a step better, each below a step worse. */
  const dt = spec.tier - t.tier;
  e.handling = Math.round((e.handling || 0) + 2 * dt);
  e.snap = Math.max(0, Math.round((e.snap || 0) - dt));
  if (e.mag) e.mag = Math.max(1, Math.round(e.mag * (1 + 0.12 * dt)));
  if (e.charge) e.charge = e.mag;
  const out = { id: spec.id, name: spec.name, category: 'weapon', slot: 'primary', family: spec.family, tier: spec.tier,
                cost: 0, bulk: t.bulk, effects: e, price_model: spec.tier === 5 ? 'scarcity' : 'formula', legality: 'legal',
                identity: spec.identity, type: spec.type };
  if (spec.tier === 5) { out.exotic = true; out.cost = spec.cost; }
  return out;
}

