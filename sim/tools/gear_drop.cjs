let added = 0;
const fresh = new Set();
for (const w of WEAPONS) if (!have.has(w.id)) { L.push(weapon(w)); fresh.add(w.id); added++; }
for (const a of ARMOUR) if (!have.has(a.id)) {
  L.push({ id: a.id, name: a.name, category: 'armor', slot: 'armor', tier: a.tier, cost: 0, bulk: a.bulk, effects: a.effects,
           price_model: 'formula', legality: 'legal', identity: a.identity }); added++;
}
for (const s of SIDEARMS) if (!have.has(s.id)) {
  const t = L.find(i => i.id === s.tpl);
  const e = JSON.parse(JSON.stringify(t.effects)); e.power = s.power;
  if (s.tier >= 4) e.pen = 1;
  L.push({ id: s.id, name: s.name, category: 'weapon', slot: 'sidearm', family: s.family, tier: s.tier, cost: 0, bulk: 1, effects: e,
           price_model: 'formula', legality: 'legal', identity: s.identity, type: 'Sidearms' }); added++;
}
let moved = 0;
for (const it of L) {
  if (it.slot === 'consumable' && RETIER[it.id] != null && it.tier !== RETIER[it.id]) { it.tier = RETIER[it.id]; moved++; }
  if (it.slot === 'mod' && MOD_TIER[it.name] != null && it.tier !== MOD_TIER[it.name]) { it.tier = MOD_TIER[it.name]; moved++; }
}
/* three models the ladder measured level with the tier below get a further step of handling (measured, not guessed) */
for (const id of ['itm_drum_launcher', 'itm_tether_stunner', 'itm_starfall_carbine']) {
  const it = L.find(i => i.id === id); if (it && fresh.has(id)) { it.effects.handling += 2; it.effects.snap = Math.max(0, it.effects.snap - 1); }
}
/* prices from the catalogue's own formula */
const I = require('../items.js');
let priced = 0;
for (const it of L) if (it.price_model === 'formula') { const c = I.formulaCost(it); if (c !== it.cost) { it.cost = c; priced++; } }
fs.writeFileSync(FILE, JSON.stringify(data, null, 1) + '\n');
console.log('added', added, 'retiered', moved, 'repriced', priced, 'total', L.length);
